package com.li.taczpronehitbox.shape;

import com.li.taczpronehitbox.config.ProneHitboxConfig;
import com.li.taczpronehitbox.prone.ProneSample;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.phys.AABB;
import net.minecraft.world.phys.Vec3;

/**
 * Oriented body box of a prone player.
 *
 * <p>Local frame: X = left/right, Y = up, Z = body forward (head direction).
 * The box is built once per hit test / render frame and is cheap to query.</p>
 *
 * <p>This is intentionally NOT an AABB: rotating an AABB around Y must either grow
 * (which is the "sideways hitbox becomes huge" bug) or be re-computed every frame.
 * The hit tests here work directly against the oriented box, so its size never
 * changes with yaw.</p>
 */
public final class ProneShape {

    private final Vec3 anchor;
    private final float yawDeg;
    private final double halfWidth;
    private final double height;
    private final double halfLength;
    private final double baseHeight;
    private final double forwardOffset;
    private final double headHalfWidth;
    private final double headLength;
    private final double headMinY;
    private final double headMaxY;

    private final Vec3 forward;
    private final Vec3 right;

    // Local box (relative to anchor).
    private final double minX;
    private final double maxX;
    private final double minY;
    private final double maxY;
    private final double minZ;
    private final double maxZ;

    private ProneShape(Vec3 anchor, float yawDeg,
                       double halfWidth, double height, double halfLength,
                       double baseHeight, double forwardOffset,
                       double headHalfWidth, double headLength,
                       double headMinY, double headMaxY) {
        this.anchor = anchor;
        this.yawDeg = yawDeg;
        this.halfWidth = halfWidth;
        this.height = height;
        this.halfLength = halfLength;
        this.baseHeight = baseHeight;
        this.forwardOffset = forwardOffset;
        this.headHalfWidth = headHalfWidth;
        this.headLength = headLength;
        this.headMinY = headMinY;
        this.headMaxY = headMaxY;

        double yawRad = Math.toRadians(yawDeg);
        this.forward = new Vec3(-Math.sin(yawRad), 0.0D, Math.cos(yawRad));
        this.right = new Vec3(Math.cos(yawRad), 0.0D, Math.sin(yawRad));

        this.minX = -halfWidth;
        this.maxX = halfWidth;
        this.minY = baseHeight;
        this.maxY = baseHeight + height;
        this.minZ = -halfLength;
        this.maxZ = halfLength;
    }

    /** Current shape of a player (no ping compensation). */
    public static ProneShape forPlayer(Player player) {
        return fromSample(com.li.taczpronehitbox.prone.ProneHistory.current(player));
    }

    /** Build a shape from a recorded player sample (position + body yaw). */
    public static ProneShape fromSample(ProneSample sample) {
        double width = configDouble(ProneHitboxConfig.COMMON != null ? ProneHitboxConfig.COMMON.bodyWidth : null, 0.65D);
        double height = configDouble(ProneHitboxConfig.COMMON != null ? ProneHitboxConfig.COMMON.bodyHeight : null, 0.50D);
        double length = configDouble(ProneHitboxConfig.COMMON != null ? ProneHitboxConfig.COMMON.bodyLength : null, 1.80D);
        double offset = configDouble(ProneHitboxConfig.COMMON != null ? ProneHitboxConfig.COMMON.forwardOffset : null, 0.0D);
        double base = configDouble(ProneHitboxConfig.COMMON != null ? ProneHitboxConfig.COMMON.baseHeight : null, 0.0D);
        double headWidth = configDouble(ProneHitboxConfig.COMMON != null ? ProneHitboxConfig.COMMON.headWidth : null, 0.65D);
        double headLength = configDouble(ProneHitboxConfig.COMMON != null ? ProneHitboxConfig.COMMON.headLength : null, 0.60D);
        double headHeight = configDouble(ProneHitboxConfig.COMMON != null ? ProneHitboxConfig.COMMON.headHeight : null, 0.30D);
        double headVerticalOffset = configDouble(ProneHitboxConfig.COMMON != null ? ProneHitboxConfig.COMMON.headVerticalOffset : null, 0.0D);

        // Migration: configs generated by <=1.2.3 still contain the old short box
        // (1.45 long, centre 0.52 from the feet), which only covered the legs/chest.
        // If the user has not customised the shape, upgrade those exact legacy values
        // to the whole-body box instead of forcing them to edit the config.
        if (isLegacyShape(width, height, length, offset, base)
                || isPreviousWholeBodyShape(width, height, length, offset, base)) {
            // Whole-body box centred on the entity origin; the custom prone renderer places
            // the model inside this exact box, so both always match.
            width = 0.65D;
            height = 0.50D;
            length = 1.80D;
            offset = 0.0D;
            base = 0.0D;
        }

        // Migrate old small/centred head-box defaults to the reference head box.
        if (Math.abs(headWidth - 0.36D) < 1.0E-6D
                && Math.abs(headLength - 0.35D) < 1.0E-6D
                && Math.abs(headHeight - 0.40D) < 1.0E-6D) {
            headWidth = 0.65D;
            headLength = 0.60D;
            headHeight = 0.30D;
        } else if (Math.abs(headWidth - 0.50D) < 1.0E-6D
                && Math.abs(headLength - 0.50D) < 1.0E-6D
                && Math.abs(headHeight - 0.40D) < 1.0E-6D) {
            headWidth = 0.65D;
            headLength = 0.60D;
            headHeight = 0.30D;
        }

        float yaw = sample.bodyYaw();
        double yawRad = Math.toRadians(yaw);
        Vec3 forward = new Vec3(-Math.sin(yawRad), 0.0D, Math.cos(yawRad));
        Vec3 anchor = sample.pos().add(forward.scale(offset));
        // The model's head is at local +Z. The reference drawing puts the red head box
        // inside that end of the white body box, with both top faces aligned.
        double clampedHeadHeight = Math.max(0.05D, headHeight);
        double headTop = base + height + headVerticalOffset;
        double headBottom = headTop - clampedHeadHeight;
        return new ProneShape(anchor, yaw, width / 2.0D, height, length / 2.0D, base, offset,
                Math.min(width / 2.0D, headWidth / 2.0D), Math.min(length, Math.max(0.05D, headLength)),
                headBottom, headTop);
    }

    /** The whole-body defaults shipped by 1.2.4-1.2.6 (centre in front of the entity origin). */
    private static boolean isPreviousWholeBodyShape(double width, double height, double length,
                                                    double offset, double base) {
        return Math.abs(width - 0.65D) < 1.0E-6D
                && Math.abs(height - 0.50D) < 1.0E-6D
                && Math.abs(length - 1.80D) < 1.0E-6D
                && Math.abs(offset - 0.90D) < 1.0E-6D
                && Math.abs(base - 0.0D) < 1.0E-6D;
    }

    /** True when the config still holds the pre-1.2.4 default shape, untouched by the user. */
    private static boolean isLegacyShape(double width, double height, double length,
                                         double offset, double base) {
        return Math.abs(width - 0.68D) < 1.0E-6D
                && Math.abs(height - 0.55D) < 1.0E-6D
                && Math.abs(length - 1.45D) < 1.0E-6D
                && Math.abs(offset - 0.52D) < 1.0E-6D
                && Math.abs(base - 0.02D) < 1.0E-6D;
    }

    private static double configDouble(Object value, double fallback) {
        if (value instanceof net.minecraftforge.common.ForgeConfigSpec.DoubleValue doubleValue) {
            try {
                return doubleValue.get();
            } catch (IllegalStateException e) {
                return fallback;
            }
        }
        return fallback;
    }

    /** World-space ray vs the union of the body box and the head box. Returns the hit point or null. */
    public Vec3 clip(Vec3 from, Vec3 to) {
        Vec3 start = toLocal(from);
        Vec3 end = toLocal(to);
        double bodyT = clipBox(start, end, new AABB(minX, minY, minZ, maxX, maxY, maxZ));
        double headT = clipBox(start, end, localHeadBox());
        double t;
        if (bodyT < 0.0D) {
            t = headT;
        } else if (headT < 0.0D) {
            t = bodyT;
        } else {
            t = Math.min(bodyT, headT);
        }
        if (t < 0.0D) {
            return null;
        }
        Vec3 local = new Vec3(
                start.x + (end.x - start.x) * t,
                start.y + (end.y - start.y) * t,
                start.z + (end.z - start.z) * t);
        return toWorld(local);
    }

    /** Slab test against one local AABB; returns the entry t or -1. */
    private static double clipBox(Vec3 start, Vec3 end, AABB box) {
        double[] interval = new double[] {0.0D, 1.0D};
        if (!clipAxis(start.x, end.x - start.x, box.minX, box.maxX, interval)
                || !clipAxis(start.y, end.y - start.y, box.minY, box.maxY, interval)
                || !clipAxis(start.z, end.z - start.z, box.minZ, box.maxZ, interval)) {
            return -1.0D;
        }
        return interval[0];
    }

    /** Slab test for one axis; updates [tMin, tMax] in place. */
    private static boolean clipAxis(double start, double dir, double min, double max, double[] interval) {
        if (Math.abs(dir) < 1.0E-9D) {
            return start >= min && start <= max;
        }
        double inv = 1.0D / dir;
        double t1 = (min - start) * inv;
        double t2 = (max - start) * inv;
        if (t1 > t2) {
            double tmp = t1;
            t1 = t2;
            t2 = tmp;
        }
        double tMin = Math.max(interval[0], t1);
        double tMax = Math.min(interval[1], t2);
        if (tMin > tMax) {
            return false;
        }
        interval[0] = tMin;
        interval[1] = tMax;
        return true;
    }

    /** True if the world point is inside the body box. */
    public boolean contains(Vec3 world) {
        Vec3 local = toLocal(world);
        return local.x >= minX && local.x <= maxX
                && local.y >= minY && local.y <= maxY
                && local.z >= minZ && local.z <= maxZ;
    }

    /** True if the hit point is inside the head box at the body's +Z (head) end. */
    public boolean isHeadshot(Vec3 world) {
        Vec3 local = toLocal(world);
        double eps = 1.0E-9D;
        return local.x >= -headHalfWidth - eps && local.x <= headHalfWidth + eps
                && local.y >= headMinY - eps && local.y <= headMaxY + eps
                && local.z >= maxZ - headLength - eps && local.z <= maxZ + eps;
    }

    public Vec3 toLocal(Vec3 world) {
        Vec3 delta = world.subtract(anchor);
        return new Vec3(
                delta.x * right.x + delta.z * right.z,
                delta.y,
                delta.x * forward.x + delta.z * forward.z
        );
    }

    public Vec3 toWorld(Vec3 local) {
        return anchor
                .add(right.scale(local.x))
                .add(new Vec3(0.0D, local.y, 0.0D))
                .add(forward.scale(local.z));
    }

    /** AABB that encloses the oriented box; only for quick culling. */
    public AABB enclosingAabb() {
        double extentX = halfWidth * Math.abs(right.x) + halfLength * Math.abs(forward.x);
        double extentZ = halfWidth * Math.abs(right.z) + halfLength * Math.abs(forward.z);
        return new AABB(
                anchor.x - extentX, anchor.y + minY, anchor.z - extentZ,
                anchor.x + extentX, anchor.y + maxY, anchor.z + extentZ);
    }

    public Vec3 anchor() {
        return anchor;
    }

    public float yawDeg() {
        return yawDeg;
    }

    public double halfWidth() {
        return halfWidth;
    }

    public double height() {
        return height;
    }

    public double halfLength() {
        return halfLength;
    }

    public double forwardOffset() {
        return forwardOffset;
    }

    public double baseHeight() {
        return baseHeight;
    }

    @Deprecated
    public double headFrontFraction() {
        return headLength / (maxZ - minZ);
    }

    /** Local box, relative to {@link #anchor()} (use for debug rendering). */
    public AABB localBox() {
        return new AABB(minX, minY, minZ, maxX, maxY, maxZ);
    }

    /** Local head box inside the +Z (head) end, relative to {@link #anchor()}. */
    public AABB localHeadBox() {
        return new AABB(-headHalfWidth, headMinY, maxZ - headLength,
                headHalfWidth, headMaxY, maxZ);
    }
}